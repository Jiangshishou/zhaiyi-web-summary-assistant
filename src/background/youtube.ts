// YouTube subtitle extraction via page/watch metadata, InnerTube player, and timedtext fallback.
// The important bit is breadth: try several caption candidates and several timedtext formats
// before declaring that YouTube has no readable subtitles.
import type { SubtitleSegment } from "../shared/types";
import {
  buildTranslatedYouTubeCaptionCandidates,
  buildYouTubeCaptionFetchUrls,
  createYouTubeTranscriptStageDiagnostic,
  extractYouTubeVideoId,
  isYouTubeVideoId,
  normalizeYouTubeTranscriptResult,
  parseYouTubeTimedText,
  rankYouTubeCaptionCandidates,
  type YouTubeTranscriptResult,
  type YouTubeTranscriptStageDiagnostic
} from "../shared/youtubeTranscript";

const INNERTUBE_API_URL = "https://www.youtube.com/youtubei/v1/player";
const INNERTUBE_NEXT_URL = "https://www.youtube.com/youtubei/v1/next";
const INNERTUBE_TRANSCRIPT_URL = "https://www.youtube.com/youtubei/v1/get_transcript";
const WATCH_URL = "https://www.youtube.com/watch?v={video_id}";
const MAX_CAPTION_ATTEMPTS = 3;
const MAX_TRANSLATION_TARGETS = 2;
const MAX_TRANSLATION_SOURCE_TRACKS = 2;
const WEB_CLIENT = { name: "web", clientName: "WEB", clientVersion: "2.20251209.01.00", clientNameHeader: "1" };
const INNERTUBE_CLIENTS = [
  WEB_CLIENT,
  { name: "android", clientName: "ANDROID", clientVersion: "20.10.38", clientNameHeader: "3" },
  { name: "ios", clientName: "IOS", clientVersion: "20.10.4", clientNameHeader: "5" },
  { name: "mweb", clientName: "MWEB", clientVersion: "2.20251209.01.00", clientNameHeader: "2" }
];

type SubtitleResult = { text: string; segments: SubtitleSegment[] };

type CaptionCandidate = {
  baseUrl: string;
  languageCode: string;
  kind: string;
  name: string;
  index: number;
  isAutoGenerated: boolean;
  isTranslated: boolean;
  isTranslatable: boolean;
};

type YouTubeDiagnosticStage = YouTubeTranscriptStageDiagnostic;

type YouTubeDiagnostic = {
  videoId: string;
  stages: {
    dom: YouTubeDiagnosticStage;
    watch_html: YouTubeDiagnosticStage;
    innertube: YouTubeDiagnosticStage;
    caption: YouTubeDiagnosticStage;
  };
};

type CaptionAttemptResult = {
  result?: { text: string; segments: SubtitleSegment[]; isAutoGenerated: boolean; languageCode: string };
  errors: string[];
};

type YouTubeSubtitleResponse = YouTubeTranscriptResult;
type CachedYouTubeSubtitle = {
  expiresAt: number;
  response: YouTubeSubtitleResponse;
};

const TRANSCRIPT_CACHE_TTL_MS = 5 * 60 * 1000;
const transcriptCache = new Map<string, CachedYouTubeSubtitle>();
const inFlightTranscripts = new Map<string, Promise<YouTubeSubtitleResponse | undefined>>();

export async function fetchYouTubeSubtitle(
  pageUrl: string
): Promise<YouTubeSubtitleResponse | undefined> {
  const videoId = extractYouTubeVideoId(pageUrl);
  if (!videoId) {
    console.warn("[YouMind] youtube-bg: no valid video id", pageUrl);
    return undefined;
  }

  const cached = readCachedTranscript(videoId);
  if (cached) return cached;

  const inFlight = inFlightTranscripts.get(videoId);
  if (inFlight) return inFlight;

  const promise = fetchYouTubeSubtitleUncached(pageUrl, videoId)
    .then((response) => {
      if (response?.text) cacheTranscript(videoId, response);
      return response;
    })
    .finally(() => {
      inFlightTranscripts.delete(videoId);
    });
  inFlightTranscripts.set(videoId, promise);
  return promise;
}

export function clearYouTubeSubtitleCacheForTests(): void {
  transcriptCache.clear();
  inFlightTranscripts.clear();
}

async function fetchYouTubeSubtitleUncached(
  pageUrl: string,
  videoId: string
): Promise<YouTubeSubtitleResponse | undefined> {
  const diagnosticStartedAt = Date.now();
  const diagnostic = createYouTubeDiagnostic(videoId);
  const watchStartedAt = Date.now();
  const watchHtml = await fetchWatchPage(videoId, pageUrl);
  const watchDurationMs = elapsedMs(watchStartedAt);
  if (!watchHtml) {
    diagnostic.stages.watch_html = createYouTubeTranscriptStageDiagnostic(watchStartedAt, { ok: false, error: "watch page fetch failed" });
    logYouTubeDiagnostic(diagnostic, false, diagnosticStartedAt);
    return undefined;
  }

  const captionStartedAt = Date.now();
  const apiKey = extractApiKey(watchHtml);
  const playerResponses: unknown[] = [];
  const watchPlayerResponse = extractPlayerResponse(watchHtml);
  const watchTranscriptParams = [
    findTranscriptParams(extractInitialData(watchHtml)),
    findTranscriptParams(watchPlayerResponse)
  ];
  const watchTrackCount = readCaptionTracks(watchPlayerResponse).length;
  if (watchHtml.includes("Sign in to confirm") || watchHtml.includes("not a bot")) {
    diagnostic.stages.watch_html = {
      ok: false,
      durationMs: watchDurationMs,
      candidateCount: watchTrackCount,
      error: "bot-check response"
    };
  } else if (isMatchingPlayerResponse(watchPlayerResponse, videoId)) {
    playerResponses.push(watchPlayerResponse);
    diagnostic.stages.watch_html = createYouTubeTranscriptStageDiagnostic(watchStartedAt, { ok: true, candidateCount: watchTrackCount });
  } else if (watchPlayerResponse) {
    diagnostic.stages.watch_html = {
      ok: false,
      durationMs: watchDurationMs,
      candidateCount: watchTrackCount,
      error: `stale watch playerResponse: ${getPlayerResponseVideoId(watchPlayerResponse) ?? "unknown"}`
    };
    console.warn("[YouMind] youtube-bg: stale watch playerResponse ignored", {
      expectedVideoId: videoId,
      actualVideoId: getPlayerResponseVideoId(watchPlayerResponse)
    });
  } else {
    diagnostic.stages.watch_html = createYouTubeTranscriptStageDiagnostic(watchStartedAt, {
      ok: false,
      candidateCount: 0,
      error: "ytInitialPlayerResponse missing"
    });
  }

  const watchCandidates = collectCaptionCandidates(playerResponses);
  const attemptedCaptionCandidates = new Set<string>();
  if (watchCandidates.length) {
    const watchTranscript = await fetchBestTimedTextTranscript(watchCandidates, videoId, attemptedCaptionCandidates);
    if (watchTranscript.result) {
      diagnostic.stages.innertube = {
        ok: true,
        durationMs: 0,
        candidateCount: 0,
        error: "skipped; watch_html supplied working captions"
      };
      diagnostic.stages.caption = createYouTubeTranscriptStageDiagnostic(captionStartedAt, {
        ok: true,
        candidateCount: watchCandidates.length,
        selectedLanguage: watchTranscript.result.languageCode
      });
      logYouTubeDiagnostic(diagnostic, true, diagnosticStartedAt);
      return normalizeYouTubeTranscriptResult({
        text: watchTranscript.result.text,
        segments: watchTranscript.result.segments,
        isAutoGenerated: watchTranscript.result.isAutoGenerated
      });
    }
  }

  if (apiKey) {
    const innertubeStartedAt = Date.now();
    const innertube = await fetchInnertubePlayers(videoId, apiKey, pageUrl);
    playerResponses.push(...innertube.responses);
    diagnostic.stages.innertube = {
      ok: innertube.responses.length > 0,
      durationMs: elapsedMs(innertubeStartedAt),
      candidateCount: collectCaptionCandidates(innertube.responses).length,
      ...(innertube.failures.length ? { error: innertube.failures.join("; ") } : {})
    };
  } else if (!readCaptionTracks(watchPlayerResponse).length) {
    diagnostic.stages.innertube = { ok: false, durationMs: 0, candidateCount: 0, error: "no INNERTUBE_API_KEY found" };
    console.warn("[YouMind] youtube-bg: no INNERTUBE_API_KEY found");
  } else {
    diagnostic.stages.innertube = { ok: true, durationMs: 0, candidateCount: 0, error: "skipped; watch_html supplied captions" };
  }

  const candidates = collectCaptionCandidates(playerResponses);
  if (!candidates.length) {
    diagnostic.stages.caption = createYouTubeTranscriptStageDiagnostic(captionStartedAt, {
      ok: false,
      candidateCount: 0,
      error: "no caption candidates"
    });
    logYouTubeDiagnostic(diagnostic, false, diagnosticStartedAt);
    console.warn("[YouMind] youtube-bg: no caption candidates", {
      playerResponses: playerResponses.length,
      apiKey: Boolean(apiKey)
    });
    return undefined;
  }

  const directTranscript = await fetchBestTimedTextTranscript(candidates, videoId, attemptedCaptionCandidates);
  if (directTranscript.result) {
    diagnostic.stages.caption = createYouTubeTranscriptStageDiagnostic(captionStartedAt, {
      ok: true,
      candidateCount: candidates.length,
      selectedLanguage: directTranscript.result.languageCode
    });
    logYouTubeDiagnostic(diagnostic, true, diagnosticStartedAt);
    return normalizeYouTubeTranscriptResult({
      text: directTranscript.result.text,
      segments: directTranscript.result.segments,
      isAutoGenerated: directTranscript.result.isAutoGenerated
    });
  }

  if (!apiKey) {
    diagnostic.stages.caption = createYouTubeTranscriptStageDiagnostic(captionStartedAt, {
      ok: false,
      candidateCount: candidates.length,
      selectedLanguage: candidates[0]?.languageCode,
      error: [...directTranscript.errors, "no api key for get_transcript fallback"].join("; ")
    });
    logYouTubeDiagnostic(diagnostic, false, diagnosticStartedAt);
    console.warn("[YouMind] youtube-bg: no api key for get_transcript fallback");
    return undefined;
  }

  const transcriptFallback = await fetchInnertubeTranscript(videoId, apiKey, pageUrl, watchTranscriptParams);
  diagnostic.stages.caption = transcriptFallback
    ? createYouTubeTranscriptStageDiagnostic(captionStartedAt, {
        ok: true,
        candidateCount: candidates.length,
        selectedLanguage: candidates[0]?.languageCode,
        error: "timedtext failed; get_transcript fallback succeeded"
      })
    : createYouTubeTranscriptStageDiagnostic(captionStartedAt, {
        ok: false,
        candidateCount: candidates.length,
        selectedLanguage: candidates[0]?.languageCode,
        error: [...directTranscript.errors, "get_transcript fallback failed"].join("; ")
      });
  logYouTubeDiagnostic(diagnostic, Boolean(transcriptFallback), diagnosticStartedAt);
  return normalizeYouTubeTranscriptResult({
    text: transcriptFallback?.text,
    segments: transcriptFallback?.segments,
    isAutoGenerated: transcriptFallback ? candidates[0]?.isAutoGenerated : undefined
  });
}

// --- Watch page + playerResponse discovery ---

async function fetchWatchPage(videoId: string, pageUrl?: string): Promise<string | undefined> {
  const url = WATCH_URL.replace("{video_id}", encodeURIComponent(videoId));
  const response = await fetch(url, {
    credentials: "include",
    headers: {
      Accept: "text/html,application/xhtml+xml",
      "Accept-Language": "en-US"
    },
    referrer: pageUrl ?? url
  });
  if (!response.ok) {
    console.warn("[YouMind] youtube-bg: watch page fetch failed", response.status);
    return undefined;
  }
  return response.text();
}

function extractApiKey(html: string): string | undefined {
  const match = html.match(/"INNERTUBE_API_KEY":\s*"([a-zA-Z0-9_-]+)"/);
  return match?.[1];
}

function extractPlayerResponse(html: string): unknown | undefined {
  const tokenIndex = html.indexOf("ytInitialPlayerResponse");
  if (tokenIndex < 0) return undefined;

  const jsonText = extractBalancedJson(html, html.indexOf("{", tokenIndex));
  if (!jsonText) return undefined;

  try {
    return JSON.parse(jsonText) as unknown;
  } catch {
    console.warn("[YouMind] youtube-bg: failed to parse watch playerResponse");
    return undefined;
  }
}

function extractInitialData(html: string): unknown | undefined {
  const tokenIndex = html.indexOf("ytInitialData");
  if (tokenIndex < 0) return undefined;

  const jsonText = extractBalancedJson(html, html.indexOf("{", tokenIndex));
  if (!jsonText) return undefined;

  try {
    return JSON.parse(jsonText) as unknown;
  } catch {
    console.warn("[YouMind] youtube-bg: failed to parse watch initialData");
    return undefined;
  }
}

function extractBalancedJson(text: string, firstBraceIndex: number): string | undefined {
  if (firstBraceIndex < 0) return undefined;

  let depth = 0;
  let inString = false;
  let escaped = false;
  for (let index = firstBraceIndex; index < text.length; index += 1) {
    const char = text[index];
    if (inString) {
      if (escaped) {
        escaped = false;
      } else if (char === "\\") {
        escaped = true;
      } else if (char === "\"") {
        inString = false;
      }
      continue;
    }

    if (char === "\"") {
      inString = true;
    } else if (char === "{") {
      depth += 1;
    } else if (char === "}") {
      depth -= 1;
      if (depth === 0) return text.slice(firstBraceIndex, index + 1);
    }
  }

  return undefined;
}

function isMatchingPlayerResponse(playerResponse: unknown, expectedVideoId: string): boolean {
  if (!playerResponse) return false;
  const actualVideoId = getPlayerResponseVideoId(playerResponse);
  return !actualVideoId || actualVideoId === expectedVideoId;
}

function getPlayerResponseVideoId(playerResponse: unknown): string | undefined {
  const root = readRecord(playerResponse);
  const details = readRecord(root?.videoDetails);
  const microformat = readRecord(readRecord(root?.microformat)?.playerMicroformatRenderer);
  const candidates = [details?.videoId, microformat?.externalVideoId, microformat?.videoId];
  return candidates.find(isYouTubeVideoId);
}

// --- InnerTube player API ---

async function fetchInnertubePlayers(videoId: string, apiKey: string, pageUrl: string): Promise<{ responses: unknown[]; failures: string[] }> {
  const url = `${INNERTUBE_API_URL}?key=${encodeURIComponent(apiKey)}`;
  const responses: unknown[] = [];
  const failures: string[] = [];

  for (const client of INNERTUBE_CLIENTS) {
    let data: unknown;
    try {
      const response = await fetch(url, {
        method: "POST",
        credentials: "include",
        headers: {
          Accept: "application/json",
          "Content-Type": "application/json",
          "X-YouTube-Client-Name": client.clientNameHeader,
          "X-YouTube-Client-Version": client.clientVersion
        },
        referrer: pageUrl,
        body: JSON.stringify({
          context: { client: { clientName: client.clientName, clientVersion: client.clientVersion } },
          videoId,
          contentCheckOk: true,
          racyCheckOk: true
        })
      });

      if (!response.ok) {
        failures.push(`${client.name}: HTTP ${response.status}`);
        continue;
      }

      data = await response.json() as unknown;
    } catch (error) {
      failures.push(`${client.name}: ${error instanceof Error ? error.message : String(error)}`);
      continue;
    }
    const status = readRecord(readRecord(data)?.playabilityStatus)?.status;
    if (typeof status === "string" && status !== "OK") {
      const reason = readRecord(readRecord(data)?.playabilityStatus)?.reason;
      failures.push(`${client.name}: ${status}${typeof reason === "string" ? ` - ${reason}` : ""}`);
      continue;
    }

    if (!isMatchingPlayerResponse(data, videoId)) {
      failures.push(`${client.name}: stale ${getPlayerResponseVideoId(data) ?? "unknown"}`);
      continue;
    }

    responses.push(data);
    if (readCaptionTracks(data).length > 0) break;
  }

  if (!responses.length && failures.length) {
    console.warn("[YouMind] youtube-bg: InnerTube player API failed", failures);
  }

  return { responses, failures };
}

// --- Caption candidate ranking + timedtext fetch ---

function collectCaptionCandidates(playerResponses: unknown[]): CaptionCandidate[] {
  const nativeTracks = playerResponses.flatMap((playerResponse) => readCaptionTracks(playerResponse));
  const normalizedNativeTracks = dedupeCaptionCandidates(nativeTracks.map(normalizeCaptionTrack).filter(BooleanCandidate));
  const translatedTracks = collectTranslatedCaptionCandidates(playerResponses, normalizedNativeTracks);
  return rankCaptionCandidates(dedupeCaptionCandidates([...normalizedNativeTracks, ...translatedTracks]));
}

function collectTranslatedCaptionCandidates(playerResponses: unknown[], nativeTracks: CaptionCandidate[]): CaptionCandidate[] {
  const translationLanguages = dedupeLanguages(playerResponses.flatMap(readTranslationLanguages));
  return buildTranslatedYouTubeCaptionCandidates(nativeTracks, translationLanguages, {
    maxTranslationTargets: MAX_TRANSLATION_TARGETS,
    maxSourceTracks: MAX_TRANSLATION_SOURCE_TRACKS,
    mapCandidate: (sourceTrack, target, candidate, translatedOffset) => ({
      ...candidate,
      name: target.name || target.languageCode,
      index: sourceTrack.index + nativeTracks.length + translatedOffset
    })
  });
}

function normalizeCaptionTrack(track: Record<string, unknown>, index: number): CaptionCandidate | undefined {
  if (typeof track.baseUrl !== "string" || !track.baseUrl.trim()) return undefined;
  const languageCode = typeof track.languageCode === "string" ? track.languageCode : "";
  if (!languageCode) return undefined;
  const kind = typeof track.kind === "string" ? track.kind : "";
  const vssId = typeof track.vssId === "string" ? track.vssId : "";
  const isAutoGenerated = kind === "asr" || /^a\./i.test(vssId);

  return {
    baseUrl: decodeXmlText(track.baseUrl),
    languageCode,
    kind,
    name: readText(track.name) || languageCode,
    index,
    isAutoGenerated,
    isTranslated: false,
    isTranslatable: track.isTranslatable !== false
  };
}

function rankCaptionCandidates(candidates: CaptionCandidate[]): CaptionCandidate[] {
  return rankYouTubeCaptionCandidates(candidates);
}

async function fetchBestTimedTextTranscript(
  candidates: CaptionCandidate[],
  videoId: string,
  attemptedCaptionCandidates = new Set<string>()
): Promise<CaptionAttemptResult> {
  const errors: string[] = [];
  const attempts = candidates
    .filter((candidate) => !attemptedCaptionCandidates.has(captionCandidateKey(candidate)))
    .slice(0, MAX_CAPTION_ATTEMPTS);

  for (const candidate of attempts) {
    attemptedCaptionCandidates.add(captionCandidateKey(candidate));
    if (requiresPoToken(candidate.baseUrl)) {
      errors.push(`${candidate.languageCode}: requires PoToken`);
      continue;
    }

    const transcript = await fetchTimedTextTranscript(candidate, videoId);
    if (transcript.result) {
      return {
        result: {
          ...transcript.result,
          isAutoGenerated: candidate.isAutoGenerated,
          languageCode: candidate.languageCode
        },
        errors
      };
    }
    errors.push(`${candidate.languageCode}: ${transcript.error ?? "timedtext empty or failed"}`);
  }

  console.warn("[YouMind] youtube-bg: timedtext candidates failed", errors);
  return { errors };
}

async function fetchTimedTextTranscript(candidate: CaptionCandidate, videoId: string): Promise<{ result?: SubtitleResult; error?: string }> {
  const errors: string[] = [];
  for (const transcriptUrl of buildYouTubeCaptionFetchUrls(candidate.baseUrl)) {
    const transcriptResponse = await fetch(transcriptUrl, {
      credentials: "include",
      headers: {
        Accept: "application/json, text/plain, */*",
        "Accept-Language": "en-US"
      },
      referrer: WATCH_URL.replace("{video_id}", encodeURIComponent(videoId))
    });

    if (!transcriptResponse.ok) {
      errors.push(`HTTP ${transcriptResponse.status}`);
      continue;
    }

    const { text, segments } = parseYouTubeTimedText(await transcriptResponse.text());
    if (text) return { result: { text, segments } };
    errors.push("parsed empty");
  }

  return { error: [...new Set(errors)].join(", ") || "timedtext empty or failed" };
}

function requiresPoToken(url: string): boolean {
  return /[?&]exp=xp[ev](?:&|$)/u.test(url);
}

// --- InnerTube get_transcript fallback ---

async function fetchInnertubeTranscript(
  videoId: string,
  apiKey: string,
  pageUrl: string,
  pageTranscriptParams: Array<string | undefined> = []
): Promise<SubtitleResult | undefined> {
  const pageParams = dedupeTranscriptParams(pageTranscriptParams);
  for (const params of pageParams) {
    const transcript = await fetchTranscriptByParams(params, apiKey, pageUrl);
    if (transcript) return transcript;
  }

  const nextParams = dedupeTranscriptParams([await fetchTranscriptParams(videoId, apiKey, pageUrl)])
    .filter((params) => !pageParams.includes(params));
  if (!pageParams.length && !nextParams.length) {
    console.warn("[YouMind] youtube-bg: no get_transcript params found");
    return undefined;
  }

  for (const params of nextParams) {
    const transcript = await fetchTranscriptByParams(params, apiKey, pageUrl);
    if (transcript) return transcript;
  }

  return undefined;
}

async function fetchTranscriptByParams(
  params: string,
  apiKey: string,
  pageUrl: string
): Promise<SubtitleResult | undefined> {
  const response = await fetch(`${INNERTUBE_TRANSCRIPT_URL}?key=${encodeURIComponent(apiKey)}`, {
    method: "POST",
    credentials: "include",
    headers: {
      Accept: "application/json",
      "Content-Type": "application/json",
      "X-YouTube-Client-Name": WEB_CLIENT.clientNameHeader,
      "X-YouTube-Client-Version": WEB_CLIENT.clientVersion
    },
    referrer: pageUrl,
    body: JSON.stringify({
      context: { client: { clientName: WEB_CLIENT.clientName, clientVersion: WEB_CLIENT.clientVersion } },
      params
    })
  });

  if (!response.ok) {
    console.warn("[YouMind] youtube-bg: get_transcript failed", response.status);
    return undefined;
  }

  const parsed = parseInnertubeTranscript(await response.json() as unknown);
  if (!parsed.text) {
    console.warn("[YouMind] youtube-bg: get_transcript parsed empty");
    return undefined;
  }

  return parsed;
}

function dedupeTranscriptParams(params: Array<string | undefined>): string[] {
  const seen = new Set<string>();
  return params.filter((value): value is string => {
    if (!value || seen.has(value)) return false;
    seen.add(value);
    return true;
  });
}

async function fetchTranscriptParams(videoId: string, apiKey: string, pageUrl: string): Promise<string | undefined> {
  const response = await fetch(`${INNERTUBE_NEXT_URL}?key=${encodeURIComponent(apiKey)}`, {
    method: "POST",
    credentials: "include",
    headers: {
      Accept: "application/json",
      "Content-Type": "application/json",
      "X-YouTube-Client-Name": WEB_CLIENT.clientNameHeader,
      "X-YouTube-Client-Version": WEB_CLIENT.clientVersion
    },
    referrer: pageUrl,
    body: JSON.stringify({
      context: { client: { clientName: WEB_CLIENT.clientName, clientVersion: WEB_CLIENT.clientVersion } },
      videoId,
      contentCheckOk: true,
      racyCheckOk: true
    })
  });

  if (!response.ok) {
    console.warn("[YouMind] youtube-bg: next transcript params failed", response.status);
    return undefined;
  }

  return findTranscriptParams(await response.json() as unknown);
}

// --- InnerTube transcript parser ---

function parseInnertubeTranscript(data: unknown): SubtitleResult {
  const segments: SubtitleSegment[] = [];
  collectTranscriptSegments(data, segments);

  const normalizedSegments = segments
    .filter((segment) => segment.text.trim())
    .sort((a, b) => a.start - b.start);

  return {
    text: normalizedSegments.map((segment) => segment.text).join("\n").trim(),
    segments: normalizedSegments
  };
}

function collectTranscriptSegments(value: unknown, segments: SubtitleSegment[]): void {
  if (Array.isArray(value)) {
    for (const item of value) collectTranscriptSegments(item, segments);
    return;
  }

  const record = readRecord(value);
  if (!record) return;

  const cueRenderer = readRecord(record.transcriptCueRenderer);
  if (cueRenderer) {
    const segment = readCueRendererSegment(cueRenderer);
    if (segment) segments.push(segment);
    return;
  }

  const segmentRenderer = readRecord(record.transcriptSegmentRenderer);
  if (segmentRenderer) {
    const segment = readSegmentRendererSegment(segmentRenderer);
    if (segment) segments.push(segment);
    return;
  }

  for (const nested of Object.values(record)) {
    collectTranscriptSegments(nested, segments);
  }
}

function readCueRendererSegment(record: Record<string, unknown>): SubtitleSegment | undefined {
  const text = readText(record.cue).trim();
  const start = readMilliseconds(record.startOffsetMs ?? record.startMs);
  const duration = readMilliseconds(record.durationMs);
  if (!text || start === undefined) return undefined;
  return { start: start / 1000, end: (start + (duration ?? 0)) / 1000, text };
}

function readSegmentRendererSegment(record: Record<string, unknown>): SubtitleSegment | undefined {
  const text = readText(record.snippet).trim();
  const start = readMilliseconds(record.startMs);
  const end = readMilliseconds(record.endMs);
  const duration = readMilliseconds(record.durationMs);
  if (!text || start === undefined) return undefined;
  return { start: start / 1000, end: (end ?? start + (duration ?? 0)) / 1000, text };
}

// --- Helpers ---

function readCaptionTracks(playerData: unknown): Array<Record<string, unknown>> {
  const captions = readRecord(playerData)?.captions;
  const renderer = readRecord(readRecord(captions)?.playerCaptionsTracklistRenderer);
  return readArray(renderer?.captionTracks).map(readRecord).filter(BooleanRecord);
}

function readTranslationLanguages(playerData: unknown): Array<{ languageCode: string; name: string }> {
  const captions = readRecord(playerData)?.captions;
  const renderer = readRecord(readRecord(captions)?.playerCaptionsTracklistRenderer);
  return readArray(renderer?.translationLanguages)
    .map(readRecord)
    .filter(BooleanRecord)
    .map((language) => ({
      languageCode: typeof language.languageCode === "string" ? language.languageCode : "",
      name: readText(language.languageName)
    }))
    .filter((language) => language.languageCode);
}

function dedupeCaptionCandidates(candidates: CaptionCandidate[]): CaptionCandidate[] {
  const seen = new Set<string>();
  return candidates.filter((candidate) => {
    const key = captionCandidateKey(candidate);
    if (seen.has(key)) return false;
    seen.add(key);
    return true;
  });
}

function captionCandidateKey(candidate: CaptionCandidate): string {
  return `${candidate.languageCode}|${candidate.kind}|${candidate.baseUrl}`;
}

function dedupeLanguages(languages: Array<{ languageCode: string; name: string }>): Array<{ languageCode: string; name: string }> {
  const seen = new Set<string>();
  return languages.filter((language) => {
    if (seen.has(language.languageCode)) return false;
    seen.add(language.languageCode);
    return true;
  });
}

function createYouTubeDiagnostic(videoId: string): YouTubeDiagnostic {
  return {
    videoId,
    stages: {
      dom: {
        ok: false,
        durationMs: 0,
        error: "background fallback reached after content/page extraction missed subtitles"
      },
      watch_html: { ok: false },
      innertube: { ok: false },
      caption: { ok: false }
    }
  };
}

function logYouTubeDiagnostic(diagnostic: YouTubeDiagnostic, ok: boolean, startedAt: number): void {
  console.info("[YouMind] youtube-bg diagnostic", { ok, totalDurationMs: elapsedMs(startedAt), ...diagnostic });
}

function readCachedTranscript(videoId: string): YouTubeSubtitleResponse | undefined {
  const cached = transcriptCache.get(videoId);
  if (!cached) return undefined;
  if (cached.expiresAt <= Date.now()) {
    transcriptCache.delete(videoId);
    return undefined;
  }
  return cached.response;
}

function cacheTranscript(videoId: string, response: YouTubeSubtitleResponse): void {
  transcriptCache.set(videoId, {
    response,
    expiresAt: Date.now() + TRANSCRIPT_CACHE_TTL_MS
  });
}

function elapsedMs(startedAt: number): number {
  return Math.max(0, Date.now() - startedAt);
}

function findTranscriptParams(value: unknown): string | undefined {
  if (Array.isArray(value)) {
    for (const item of value) {
      const params = findTranscriptParams(item);
      if (params) return params;
    }
    return undefined;
  }

  const record = readRecord(value);
  if (!record) return undefined;

  const endpoint = readRecord(record.getTranscriptEndpoint);
  if (typeof endpoint?.params === "string") return endpoint.params;

  for (const nested of Object.values(record)) {
    const params = findTranscriptParams(nested);
    if (params) return params;
  }

  return undefined;
}

function readText(value: unknown): string {
  if (typeof value === "string") return value;

  const record = readRecord(value);
  if (!record) return "";

  if (typeof record.simpleText === "string") return record.simpleText;

  return readArray(record.runs)
    .map((run) => readRecord(run)?.text)
    .filter((text): text is string => typeof text === "string")
    .join("");
}

function readMilliseconds(value: unknown): number | undefined {
  const numberValue = typeof value === "number" ? value : typeof value === "string" ? Number(value) : NaN;
  return Number.isFinite(numberValue) ? numberValue : undefined;
}

function decodeXmlText(value: string): string {
  return value
    .replace(/&#(\d+);/g, (_match, code: string) => String.fromCodePoint(Number(code)))
    .replace(/&#x([0-9a-f]+);/gi, (_match, code: string) => String.fromCodePoint(parseInt(code, 16)))
    .replace(/&quot;/g, "\"")
    .replace(/&#39;/g, "'")
    .replace(/&apos;/g, "'")
    .replace(/&lt;/g, "<")
    .replace(/&gt;/g, ">")
    .replace(/&amp;/g, "&");
}

function readRecord(value: unknown): Record<string, unknown> | undefined {
  return typeof value === "object" && value !== null ? (value as Record<string, unknown>) : undefined;
}

function BooleanRecord(value: Record<string, unknown> | undefined): value is Record<string, unknown> {
  return Boolean(value);
}

function BooleanCandidate(value: CaptionCandidate | undefined): value is CaptionCandidate {
  return Boolean(value);
}

function readArray(value: unknown): unknown[] {
  return Array.isArray(value) ? value : [];
}

  function clickFirstCandidate(terms: string[], selectors = [
      "button",
      "[role='button']",
      "[role='menuitem']",
      "tp-yt-paper-button",
      "tp-yt-paper-item",
      "ytd-menu-service-item-renderer",
      "a"
    ]): boolean {

    const candidates = selectors.flatMap((selector) => Array.from(document.querySelectorAll<HTMLElement>(selector)));
    for (const candidate of candidates) {
      if (!isVisible(candidate)) continue;
      const label = readElementLabel(candidate).toLowerCase();
      if (!label || !terms.some((term) => label.includes(term))) continue;
      candidate.click();
      return true;
    }
    return false;
  }

  function readElementLabel(element: HTMLElement): string {
    return [
      element.getAttribute("aria-label"),
      element.getAttribute("title"),
      element.textContent
    ].filter((value): value is string => typeof value === "string").join(" ").trim();
  }

  function isVisible(element: HTMLElement): boolean {
    const style = getComputedStyle(element);
    if (style.display === "none" || style.visibility === "hidden" || style.opacity === "0") return false;
    if (element.hidden || element.getAttribute("aria-hidden") === "true") return false;
    const rect = element.getBoundingClientRect();
    if (rect.width > 0 || rect.height > 0 || Boolean(element.offsetParent)) return true;
    return navigator.userAgent.toLowerCase().includes("jsdom") && Boolean(readElementLabel(element));
  }

import { sendRuntimeMessage } from "./sendMessage";
import { buildSourcePayload } from "./sourcePayload";
import { findScriptJson } from "./scriptJson";
import { acquireYouTubeTranscript } from "./youtubeTranscriptAcquisition";
import { readArray, readRecord } from "../shared/jsonRead";
import type { BilibiliSubtitleCandidateHint, BilibiliSubtitleHints, SourceExtractionDiagnostics, SourcePayload, SubtitleSegment } from "../shared/types";
import { classifySourcePage, type SourcePageClassification } from "./sourcePlatform";

export async function extractVideoTranscript(
  doc: Document,
  pageUrl: string,
  classification: SourcePageClassification = classifySourcePage(pageUrl)
): Promise<SourcePayload | undefined> {
  if (!classification.transcriptCandidate) return undefined;

  if (classification.platform === "youtube") {
    return extractYouTubeTranscript(doc, pageUrl);
  }

  if (classification.platform === "bilibili") {
    return extractBilibiliTranscript(doc, pageUrl);
  }

  if (classification.platform === "douyin") {
    return extractDouyinVisibleText(doc, pageUrl);
  }

  return undefined;
}

async function extractYouTubeTranscript(doc: Document, pageUrl: string): Promise<SourcePayload | undefined> {
  const transcript = await acquireYouTubeTranscript(doc, pageUrl);
  return transcript ? buildYouTubePayload(doc, pageUrl, transcript.text, transcript.segments, transcript.isAutoGenerated) : undefined;
}

function buildYouTubePayload(
  doc: Document,
  pageUrl: string,
  text: string,
  segments: SubtitleSegment[] | undefined,
  isAutoGenerated: boolean | undefined
): SourcePayload {
  return buildSourcePayload(doc, pageUrl, {
    sourceKind: "youtube-transcript",
    text,
    segments,
    isAutoGenerated,
    extractionDiagnostics: buildTranscriptDiagnostics({
      sourceKind: "youtube-transcript",
      textLength: text.length,
      segmentCount: segments?.length,
      isAutoGenerated
    })
  });
}

async function extractBilibiliTranscript(doc: Document, pageUrl: string): Promise<SourcePayload | undefined> {
  const pageSubtitleCandidates = collectBilibiliPageSubtitleCandidates(doc);
  const hints: BilibiliSubtitleHints = {
    pageUrl,
    ...(pageSubtitleCandidates.length ? { pageSubtitleCandidates } : {})
  };
  const { text, segments, isAutoGenerated, requiresLogin, sourceKind, summaryHint } = await sendRuntimeMessage({ type: "YM_FETCH_BILIBILI_SUBTITLE", hints });
  if (!text && requiresLogin) {
  throw new Error("请先登录 Bilibili，然后刷新页面重试。");
  }
  if (!text) console.warn("[YouMind] bilibili: background returned empty text", { pageUrl });
  return text ? buildBilibiliPayload(doc, pageUrl, text, segments, isAutoGenerated, sourceKind, summaryHint) : undefined;
}

function collectBilibiliPageSubtitleCandidates(doc: Document): BilibiliSubtitleCandidateHint[] {
  const playInfo = readRecord(findScriptJson(doc, "__playinfo__"));
  const playData = readRecord(playInfo?.data) ?? playInfo;
  const initialState = readRecord(findScriptJson(doc, "__INITIAL_STATE__"));
  const videoData = readRecord(initialState?.videoData);
  const candidates = [
    ...readArray(readRecord(playInfo?.subtitle)?.subtitles),
    ...readArray(readRecord(playData?.subtitle)?.subtitles),
    ...readArray(readRecord(videoData?.subtitle)?.list)
  ].map(toBilibiliPageSubtitleCandidate).filter(isBilibiliPageSubtitleCandidate);

  const seen = new Set<string>();
  return candidates.filter((candidate) => {
    if (seen.has(candidate.subtitleUrl)) return false;
    seen.add(candidate.subtitleUrl);
    return true;
  });
}

function toBilibiliPageSubtitleCandidate(value: unknown): BilibiliSubtitleCandidateHint | undefined {
  const record = readRecord(value);
  const subtitleUrl = typeof record?.subtitle_url === "string" ? record.subtitle_url.trim() : "";
  if (!subtitleUrl) return undefined;
  const language = typeof record?.lan === "string" ? record.lan : undefined;
  const aiType = typeof record?.ai_type === "number" && Number.isFinite(record.ai_type) ? record.ai_type : undefined;
  return {
    subtitleUrl,
    ...(language ? { language } : {}),
    ...(aiType !== undefined ? { aiType } : {})
  };
}

function isBilibiliPageSubtitleCandidate(
  candidate: BilibiliSubtitleCandidateHint | undefined
): candidate is BilibiliSubtitleCandidateHint {
  return Boolean(candidate);
}

function buildBilibiliPayload(
  doc: Document,
  pageUrl: string,
  text: string,
  segments: SourcePayload["segments"],
  isAutoGenerated?: boolean,
  sourceKind: SourcePayload["sourceKind"] = "bilibili-transcript",
  summaryHint?: SourcePayload["summaryHint"]
): SourcePayload {
  return buildSourcePayload(doc, pageUrl, {
    sourceKind,
    text,
    segments,
    isAutoGenerated,
    summaryHint,
    extractionDiagnostics: buildTranscriptDiagnostics({
      sourceKind,
      textLength: text.length,
      segmentCount: segments?.length,
      isAutoGenerated,
      detail: sourceKind === "bilibili-official-summary" ? "已读取 Bilibili 官方 AI 总结。" : undefined
    })
  });
}

async function extractDouyinVisibleText(doc: Document, pageUrl: string): Promise<SourcePayload | undefined> {
  const selectors = [
    "[class*='caption']",
    "[class*='subtitle']",
    "[class*='text']",
    "[data-e2e*='caption']",
    "[data-e2e*='video-desc']"
  ];
  const matched = new Set<Element>(
    selectors.flatMap((selector) => Array.from(doc.querySelectorAll(selector)))
  );
  const text = normalizeTranscript(
    Array.from(matched)
      .filter((node) => {
        for (let parent = node.parentElement; parent; parent = parent.parentElement) {
          if (matched.has(parent)) return false;
        }
        return true;
      })
      .map((node) => node.textContent ?? "")
      .join("\n")
  );

  if (!text || text.length < 40) return undefined;

  return buildSourcePayload(doc, pageUrl, {
    sourceKind: "douyin-visible",
    text,
    warning: "抖音没有官方字幕，这里只读取画面上可见的文字",
    extractionDiagnostics: buildTranscriptDiagnostics({
      sourceKind: "douyin-visible",
      textLength: text.length,
      status: "warning",
      detail: "抖音只读取页面可见文字，不保证完整。"
    })
  });
}

function buildTranscriptDiagnostics(input: {
  sourceKind: SourcePayload["sourceKind"];
  textLength: number;
  segmentCount?: number;
  isAutoGenerated?: boolean;
  status?: "success" | "warning";
  detail?: string;
}): SourceExtractionDiagnostics {
  return {
    stages: [
      {
        id: "transcript",
        status: input.status ?? "success",
        label: "字幕获取",
      detail: input.detail ?? "已读取视频字幕。",
        facts: [
          { label: "来源类型", value: input.sourceKind },
          { label: "文本长度", value: String(input.textLength) },
          ...(typeof input.segmentCount === "number" ? [{ label: "时间段", value: String(input.segmentCount) }] : []),
          ...(input.isAutoGenerated ? [{ label: "字幕类型", value: "自动生成" }] : [])
        ]
      },
      {
        id: "truncation",
        status: "success",
        label: "截断",
        detail: "字幕抽取阶段未截断来源文本。"
      }
    ]
  };
}

function normalizeTranscript(text: string): string {
  return text
    .replace(/\s+\n/g, "\n")
    .replace(/\n{3,}/g, "\n\n")
    .replace(/[ \t]{2,}/g, " ")
    .trim();
}

import { findAuthorAvatar } from "./avatar";
import { findAuthorName } from "./author";
import type { SourcePayload } from "../shared/types";

type SourcePayloadInput = {
  sourceKind: SourcePayload["sourceKind"];
  text: string;
  sourceMarkdown?: string;
  sourceText?: string;
  segments?: SourcePayload["segments"];
  isAutoGenerated?: boolean;
  summaryHint?: SourcePayload["summaryHint"];
  warning?: string;
  extractionDiagnostics?: SourcePayload["extractionDiagnostics"];
};

export function buildSourcePayload(doc: Document, pageUrl: string, input: SourcePayloadInput): SourcePayload {
  const payload: SourcePayload = {
    url: pageUrl,
    title: findSourceTitle(doc),
    ...buildSourceMetadata(doc, pageUrl),
    sourceKind: input.sourceKind,
    text: input.text,
    capturedAt: Date.now()
  };

  if (input.sourceMarkdown !== undefined) payload.sourceMarkdown = input.sourceMarkdown;
  if (input.sourceText !== undefined) payload.sourceText = input.sourceText;
  if (input.segments !== undefined) payload.segments = input.segments;
  if (input.isAutoGenerated !== undefined) payload.isAutoGenerated = input.isAutoGenerated;
  if (input.summaryHint !== undefined) payload.summaryHint = input.summaryHint;
  if (input.warning !== undefined) payload.warning = input.warning;
  if (input.extractionDiagnostics !== undefined) payload.extractionDiagnostics = input.extractionDiagnostics;

  return payload;
}

export function buildSourceMetadata(
  doc: Document,
  pageUrl: string
): Pick<SourcePayload, "authorName" | "authorAvatar" | "favicon" | "cover" | "published" | "site" | "language"> {
  return {
    authorName: findAuthorName(doc, pageUrl),
    authorAvatar: findAuthorAvatar(doc, pageUrl),
    favicon: findFavicon(doc),
    cover: findCoverImage(doc, pageUrl),
    published: findPublished(doc),
    site: findSiteName(doc),
    language: findLanguage(doc)
  };
}

/* 页面元信息的唯一入口：抽取层与空态卡都走这里，避免两套判定各写一遍而漂移。
   只读文档里的 meta/link，不触碰正文，空态下也能直接调用。 */
export function readPageMeta(
  doc: Document,
  pageUrl: string
): { site?: string; favicon?: string; cover?: string } {
  return {
    site: findSiteName(doc),
    favicon: findFavicon(doc),
    cover: findCoverImage(doc, pageUrl)
  };
}

/* 封面只有两档来源：开放图谱优先，推特卡片兜底。
   两者都拿不到就明确返回 undefined，让调用方退到占位，而不是给空串。
   相对地址按当前页面地址解析成绝对地址，缓存里存的是可直接用的地址。 */
function findCoverImage(doc: Document, pageUrl: string): string | undefined {
  const raw =
    firstMeta(doc, "property", "og:image") ||
    firstMeta(doc, "name", "twitter:image") ||
    firstMeta(doc, "property", "twitter:image");
  const value = raw?.trim();
  if (!value) return undefined;
  try {
    return new URL(value, pageUrl).href;
  } catch {
    return undefined;
  }
}

// —— defuddle MetadataExtractor 移植（task defuddle-metadata）——
// findPublished 链：meta publishDate → article:published_time → time 元素(datetime|text)
// → 兜底 h1 邻域 <time>；中文日期（2026年8月10日 / 2026-08-10）也认。
function findPublished(doc: Document): string | undefined {
  const metaValue =
    firstMeta(doc, "name", "publishDate") ||
    firstMeta(doc, "property", "article:published_time") ||
    doc.querySelector("abbr[itemprop='datePublished']")?.getAttribute("title")?.trim() ||
    firstMeta(doc, "name", "sailthru.date");
  if (metaValue) return metaValue || undefined;
  // <time> 元素：跳过指向其他页面(相关推荐卡片)的日期
  for (const t of Array.from(doc.querySelectorAll("time"))) {
    if (t.closest("a[href]")) continue;
    const v = t.getAttribute("datetime")?.trim() || t.textContent?.trim() || "";
    if (v) return v;
  }
  // h1 邻域 <time>/<p> 里的可解析日期（中文站点常见）
  const h1 = doc.querySelector("h1");
  if (h1) {
    for (const sib of [h1.nextElementSibling, h1.parentElement?.nextElementSibling]) {
      if (!sib) continue;
      for (const el of Array.from(sib.querySelectorAll("time, p"))) {
        const parsed = normalizeDateText(el.textContent?.trim() ?? "");
        if (parsed) return parsed;
      }
    }
  }
  return undefined;
}

function findSiteName(doc: Document): string | undefined {
  const candidate =
    firstMeta(doc, "property", "og:site_name") || firstMeta(doc, "name", "og:site_name");
  // 过长(>6 词)的 og:site_name 常是整页标题，拒收
  return candidate && countPlainWords(candidate) <= 6 ? candidate : undefined;
}

// 中文站点缺 <html lang> 时用 og:locale 兜底，并规范化 zh_CN→zh-CN
function findLanguage(doc: Document): string | undefined {
  const raw =
    doc.documentElement?.getAttribute("lang")?.trim() ||
    firstMeta(doc, "property", "og:locale") ||
    doc.querySelector("meta[http-equiv='Content-Language' i]")?.getAttribute("content")?.trim();
  if (!raw) return undefined;
  return raw.replace(/_/g, "-");
}

function firstMeta(doc: Document, attr: "name" | "property", value: string): string | undefined {
  const el = doc.querySelector<HTMLMetaElement>(`meta[${attr}="${value}"]`);
  return el?.content?.trim();
}

function countPlainWords(s: string): number {
  return s.trim().split(/\s+/).filter(Boolean).length;
}

// 兼容中文与 ISO 日期：`2026年8月10日`、`8月10日`、`2026-08-10…`
function normalizeDateText(text: string): string {
  const mCN = text.match(/(\d{4})\s*年\s*(\d{1,2})\s*月\s*(\d{1,2})\s*日?/);
  if (mCN) return `${mCN[1]}-${mCN[2].padStart(2, "0")}-${mCN[3].padStart(2, "0")}`;
  const mIso = text.match(/(\d{4}-\d{2}-\d{2})/);
  if (mIso) return mIso[1];
  return "";
}

function findSourceTitle(doc: Document): string {
  const headingTitle = doc.querySelector("h1")?.textContent?.trim();
  const metaTitle =
    doc.querySelector<HTMLMetaElement>('meta[name="title"]')?.content?.trim() ||
    doc.querySelector<HTMLMetaElement>('meta[property="og:title"]')?.content?.trim();
  const documentTitle = (doc.title || "").replace(/\s+-\s+YouTube\s*$/iu, "").trim();
  return headingTitle || metaTitle || documentTitle || "当前页面";
}

function findFavicon(doc: Document): string | undefined {
  return doc.querySelector<HTMLLinkElement>("link[rel~='icon'], link[rel='shortcut icon']")?.href;
}


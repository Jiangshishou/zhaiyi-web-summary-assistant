import type { SubtitleSegment } from "./types";

export type YouTubeTimedTextResult = { text: string; segments: SubtitleSegment[] };
export type YouTubeTranscriptResult = { text: string; segments?: SubtitleSegment[]; isAutoGenerated?: boolean };
export type YouTubeTranscriptStageDiagnostic = {
  ok: boolean;
  durationMs?: number;
  skipped?: boolean;
  candidateCount?: number;
  selectedLanguage?: string;
  error?: string;
};

export const YOUTUBE_CAPTION_FORMATS = ["json3", "", "srv3", "vtt"] as const;
export const DEFAULT_YOUTUBE_CAPTION_LANGUAGE_PREFERENCES = ["zh-Hans", "zh-CN", "zh", "zh-TW", "en", "en-US", "ja"] as const;

export type YouTubeCaptionCandidate = {
  baseUrl: string;
  languageCode?: string;
  kind?: string;
  index?: number;
  isAutoGenerated?: boolean;
  isTranslated?: boolean;
  isTranslatable?: boolean;
};

export type YouTubeTranslationLanguage = {
  languageCode: string;
  name?: string;
};

type DecodeText = (value: string) => string;

type TranslatedCandidateOptions<T extends YouTubeCaptionCandidate> = {
  preferredLanguages?: readonly string[];
  maxTranslationTargets?: number;
  maxSourceTracks?: number;
  mapCandidate?: (
    source: T,
    target: YouTubeTranslationLanguage,
    candidate: T,
    translatedOffset: number
  ) => T;
};

export function buildYouTubeCaptionFetchUrls(
  baseUrl: string,
  formats: readonly string[] = YOUTUBE_CAPTION_FORMATS
): string[] {
  const parsed = new URL(baseUrl);
  const stripVariantOptions = parsed.searchParams.has("variant") ? [false, true] : [false];
  const urls: string[] = [];

  for (const format of formats) {
    for (const stripVariant of stripVariantOptions) {
      const requestUrl = new URL(baseUrl);
      if (format) {
        requestUrl.searchParams.set("fmt", format);
      } else {
        requestUrl.searchParams.delete("fmt");
      }
      if (stripVariant) requestUrl.searchParams.delete("variant");
      urls.push(requestUrl.toString());
    }
  }

  return [...new Set(urls)];
}

export function normalizeYouTubeTranscriptResult(input: {
  text?: string;
  segments?: SubtitleSegment[];
  isAutoGenerated?: boolean;
}): YouTubeTranscriptResult | undefined {
  if (!input.text) return undefined;
  return {
    text: input.text,
    segments: input.segments,
    isAutoGenerated: input.isAutoGenerated
  };
}

export function createYouTubeTranscriptStageDiagnostic(
  startedAt: number,
  input: Omit<YouTubeTranscriptStageDiagnostic, "durationMs"> & { durationMs?: number }
): YouTubeTranscriptStageDiagnostic {
  return {
    ...input,
    durationMs: input.durationMs ?? Math.max(0, Date.now() - startedAt)
  };
}

export function parseYouTubeTimedText(raw: string, decodeText: DecodeText = decodeXmlText): YouTubeTimedTextResult {
  const trimmed = raw.trim();
  if (!trimmed) return { text: "", segments: [] };

  if (trimmed.startsWith("{")) {
    const json3 = parseJson3Transcript(trimmed);
    if (json3.text) return json3;
  }

  if (/^WEBVTT\b/i.test(trimmed) || trimmed.includes("-->")) {
    const vtt = parseVttTranscript(trimmed, decodeText);
    if (vtt.text) return vtt;
  }

  return parseXmlTranscript(trimmed, decodeText);
}

export function extractYouTubeVideoId(pageUrl: string): string | undefined {
  try {
    const url = new URL(pageUrl);
    const watchId = url.searchParams.get("v");
    if (isYouTubeVideoId(watchId)) return watchId;

    if (url.hostname === "youtu.be") {
      const id = url.pathname.split("/").filter(Boolean)[0];
      return isYouTubeVideoId(id) ? id : undefined;
    }

    const [kind, id] = url.pathname.split("/").filter(Boolean);
    if ((kind === "shorts" || kind === "embed" || kind === "live") && isYouTubeVideoId(id)) return id;
    return undefined;
  } catch {
    return undefined;
  }
}

export function isYouTubeVideoId(value: unknown): value is string {
  return typeof value === "string" && /^[0-9A-Za-z_-]{11}$/u.test(value);
}

export function languageMatchesPreference(value: unknown, preference: string): boolean {
  if (typeof value !== "string") return false;
  const code = normalizeLanguageCode(value);
  const preferred = normalizeLanguageCode(preference);
  if (!code || !preferred) return false;
  if (code === preferred || code.startsWith(`${preferred}-`)) return true;

  const codeBase = code.split("-")[0];
  const preferredBase = preferred.split("-")[0];
  if (codeBase !== preferredBase) return false;
  if (preferredBase !== "zh") return true;

  if (/hans|cn|sg/u.test(preferred)) return /hans|cn|sg/u.test(code);
  if (/hant|tw|hk|mo/u.test(preferred)) return /hant|tw|hk|mo/u.test(code);
  return true;
}

export function rankYouTubeCaptionCandidates<T extends YouTubeCaptionCandidate>(
  candidates: readonly T[],
  preferredLanguages: readonly string[] = DEFAULT_YOUTUBE_CAPTION_LANGUAGE_PREFERENCES
): T[] {
  return candidates
    .map((candidate, order) => ({ candidate, order }))
    .slice()
    .sort((left, right) => {
      const scoreDiff = scoreYouTubeCaptionCandidate(right.candidate, preferredLanguages) - scoreYouTubeCaptionCandidate(left.candidate, preferredLanguages);
      return scoreDiff || readCandidateIndex(left.candidate, left.order) - readCandidateIndex(right.candidate, right.order);
    })
    .map(({ candidate }) => candidate);
}

export function buildTranslatedYouTubeCaptionCandidates<T extends YouTubeCaptionCandidate>(
  tracks: readonly T[],
  translationLanguages: readonly YouTubeTranslationLanguage[],
  options: TranslatedCandidateOptions<T> = {}
): T[] {
  const preferredLanguages = options.preferredLanguages ?? DEFAULT_YOUTUBE_CAPTION_LANGUAGE_PREFERENCES;
  const maxTranslationTargets = options.maxTranslationTargets ?? 2;
  const maxSourceTracks = options.maxSourceTracks ?? 2;
  const targets = preferredLanguages
    .map((preferred) => translationLanguages.find((language) => languageMatchesPreference(language.languageCode, preferred)))
    .filter((language): language is YouTubeTranslationLanguage => Boolean(language))
    .filter((language, index, languages) => languages.findIndex((item) => item.languageCode === language.languageCode) === index)
    .slice(0, maxTranslationTargets);

  if (!targets.length) return [];

  const sourceTracks = rankYouTubeCaptionCandidates(tracks, preferredLanguages)
    .filter((track) => track.languageCode && track.isTranslatable !== false)
    .slice(0, maxSourceTracks);
  const translatedTracks: T[] = [];

  for (const sourceTrack of sourceTracks) {
    for (const target of targets) {
      if (languageMatchesPreference(sourceTrack.languageCode, target.languageCode)) continue;
      const parsed = new URL(sourceTrack.baseUrl);
      parsed.searchParams.set("tlang", target.languageCode);
      const candidate = {
        ...sourceTrack,
        baseUrl: parsed.toString(),
        languageCode: target.languageCode,
        isTranslated: true
      };
      translatedTracks.push(options.mapCandidate
        ? options.mapCandidate(sourceTrack, target, candidate, translatedTracks.length)
        : candidate);
    }
  }

  return translatedTracks;
}

function scoreYouTubeCaptionCandidate(
  candidate: YouTubeCaptionCandidate,
  preferredLanguages: readonly string[]
): number {
  let score = 0;
  for (const [index, language] of preferredLanguages.entries()) {
    if (languageMatchesPreference(candidate.languageCode, language)) {
      score = Math.max(score, 1000 - index * 80);
    }
  }

  const code = candidate.languageCode?.toLowerCase() ?? "";
  if (code.startsWith("zh")) score = Math.max(score, 850);
  if (code.startsWith("en")) score = Math.max(score, 800);
  if (!isAutoGeneratedCaptionCandidate(candidate)) score += 40;
  if (candidate.isTranslated) score -= 80;
  return score;
}

function isAutoGeneratedCaptionCandidate(candidate: YouTubeCaptionCandidate): boolean {
  return candidate.isAutoGenerated ?? candidate.kind === "asr";
}

function readCandidateIndex(candidate: YouTubeCaptionCandidate, fallback: number): number {
  return typeof candidate.index === "number" && Number.isFinite(candidate.index) ? candidate.index : fallback;
}

function parseJson3Transcript(raw: string): YouTubeTimedTextResult {
  let json: unknown;
  try {
    json = JSON.parse(raw) as unknown;
  } catch {
    return { text: "", segments: [] };
  }

  const events = readArray(readRecord(json)?.events);
  const validEvents: Array<{ tStartMs: number; dDurationMs?: number; segs: unknown[] }> = [];

  for (const event of events) {
    const record = readRecord(event);
    if (!record) continue;

    const segs = readArray(record.segs);
    const tStartMs = record.tStartMs;
    const dDurationMs = record.dDurationMs;

    if (segs.length > 0 && typeof tStartMs === "number" && Number.isFinite(tStartMs)) {
      validEvents.push({
        tStartMs,
        ...(typeof dDurationMs === "number" && Number.isFinite(dDurationMs) ? { dDurationMs } : {}),
        segs
      });
    }
  }

  const segments: SubtitleSegment[] = [];
  const lines: string[] = [];

  for (let index = 0; index < validEvents.length; index += 1) {
    const event = validEvents[index];
    const nextEvent = validEvents[index + 1];
    const start = event.tStartMs / 1000;
    const end = typeof event.dDurationMs === "number"
      ? start + event.dDurationMs / 1000
      : nextEvent ? nextEvent.tStartMs / 1000 : start;
    const text = event.segs
      .map((seg) => readRecord(seg)?.utf8)
      .filter((value): value is string => typeof value === "string")
      .join("");

    lines.push(text);
    if (text) segments.push({ start, end, text });
  }

  return {
    text: normalizeTranscript(lines.filter(Boolean).join("\n")),
    segments
  };
}

function parseXmlTranscript(raw: string, decodeText: DecodeText): YouTubeTimedTextResult {
  const segments: SubtitleSegment[] = [];
  const readAttr = (attrs: string, name: string): string => {
    const match = attrs.match(new RegExp(`${name}\\s*=\\s*(['"])(.*?)\\1`, "iu"));
    return match ? decodeText(match[2]) : "";
  };

  const pushSegment = (attrs: string, body: string, milliseconds: boolean) => {
    const text = normalizeTranscript(decodeText(body.replace(/<br\s*\/?>/gi, "\n").replace(/<[^>]+>/g, "")));
    if (!text) return;
    const startRaw = Number(readAttr(attrs, milliseconds ? "t" : "start") || 0);
    const durationRaw = Number(readAttr(attrs, milliseconds ? "d" : "dur") || 0);
    const start = milliseconds ? startRaw / 1000 : startRaw;
    const duration = milliseconds ? durationRaw / 1000 : durationRaw;
    segments.push({ start, end: start + (Number.isFinite(duration) ? duration : 0), text });
  };

  for (const match of raw.matchAll(/<text\b([^>]*)>([\s\S]*?)<\/text>/gi)) {
    pushSegment(match[1] || "", match[2] || "", false);
  }
  if (segments.length === 0) {
    for (const match of raw.matchAll(/<p\b([^>]*)>([\s\S]*?)<\/p>/gi)) {
      pushSegment(match[1] || "", match[2] || "", true);
    }
  }

  return {
    text: normalizeTranscript(segments.map((segment) => segment.text).join("\n")),
    segments
  };
}

function parseVttTranscript(raw: string, decodeText: DecodeText): YouTubeTimedTextResult {
  const segments: SubtitleSegment[] = [];
  const blocks = raw.replace(/\r\n?/g, "\n").split(/\n{2,}/);

  for (const block of blocks) {
    const lines = block.split("\n").map((line) => line.trim()).filter(Boolean);
    if (!lines.length || /^WEBVTT\b/i.test(lines[0]) || /^NOTE\b/i.test(lines[0])) continue;
    const timingIndex = lines.findIndex((line) => line.includes("-->"));
    if (timingIndex < 0) continue;
    const [startRaw, endRaw = ""] = lines[timingIndex].split("-->");
    const text = normalizeTranscript(decodeText(lines.slice(timingIndex + 1).join(" ").replace(/<[^>]+>/g, "")));
    if (!text) continue;
    const start = parseVttTimestamp(startRaw);
    const end = parseVttTimestamp(endRaw.split(/\s+/)[0] ?? "");
    segments.push({ start, end, text });
  }

  return {
    text: normalizeTranscript(segments.map((segment) => segment.text).join("\n")),
    segments
  };
}

function parseVttTimestamp(input: string): number {
  const parts = input.trim().split(":");
  if (parts.length < 2) return 0;
  const seconds = Number(parts.pop()?.replace(",", ".") ?? 0);
  const minutes = Number(parts.pop() || 0);
  const hours = Number(parts.pop() || 0);
  return hours * 3600 + minutes * 60 + seconds;
}

function normalizeTranscript(text: string): string {
  return text
    .replace(/\s+\n/g, "\n")
    .replace(/\n{3,}/g, "\n\n")
    .replace(/[ \t]{2,}/g, " ")
    .trim();
}

function normalizeLanguageCode(value: string): string {
  return value.toLowerCase().replace(/_/g, "-");
}

function decodeXmlText(value: string): string {
  return value
    .replace(/&#(\d+);/g, (_match, code: string) => String.fromCodePoint(Number(code)))
    .replace(/&#x([0-9a-f]+);/gi, (_match, code: string) => String.fromCodePoint(parseInt(code, 16)))
    .replace(/&nbsp;/g, " ")
    .replace(/&quot;/g, "\"")
    .replace(/&#39;/g, "'")
    .replace(/&apos;/g, "'")
    .replace(/&lt;/g, "<")
    .replace(/&gt;/g, ">")
    .replace(/&amp;/g, "&");
}

function readRecord(value: unknown): Record<string, unknown> | undefined {
  return typeof value === "object" && value !== null ? (value as Record<string, unknown>) : undefined;
}

function readArray(value: unknown): unknown[] {
  return Array.isArray(value) ? value : [];
}

import type {
  WebProviderStatus,
  ModelInfo,
  PageCache,
  PanelState,
  ProviderId,
  ProviderSettings,
  Settings,
  SourcePayload,
  SubtitleSegment,
  SubtitleTranslationTarget,
  SummaryCachePolicy,
  SummaryMeta,
  SummaryResult,
  TranslatedSubtitleSegment,
  BilibiliSubtitleHints,
  SourceKind
} from "./types";
import { isErrorResponse } from "./errorResponse";

type NoPayload = Record<never, never>;

type DeepseekWebProbeResponse =
  | {
      ok: true;
      status: Extract<WebProviderStatus, "available">;
      checkedAt: number;
      models?: ModelInfo[];
    }
  | {
      ok: false;
      status: Extract<WebProviderStatus, "unavailable">;
      checkedAt: number;
      error: string;
    };

type BilibiliSubtitleResponse = {
  text?: string;
  segments?: SubtitleSegment[];
  isAutoGenerated?: boolean;
  requiresLogin?: boolean;
  sourceKind?: Extract<SourceKind, "bilibili-official-summary" | "bilibili-transcript">;
  summaryHint?: SummaryResult;
};

type YouTubeTranscriptResponse = { text?: string; segments?: SubtitleSegment[]; isAutoGenerated?: boolean };

// 运行时消息的单一定义源：每个消息一条条目，type 字符串只写一次（作为 key），
// request 联合与响应映射都从这张表派生，二者不可能互相不同步。
type RuntimeContract = {
  YM_GET_SETTINGS: { request: NoPayload; response: Settings };
  YM_SAVE_SETTINGS: { request: { settings: Settings }; response: { ok: true } };
  YM_PROBE_DEEPSEEK_WEB: { request: NoPayload; response: DeepseekWebProbeResponse };
  YM_GET_PROVIDERS: { request: NoPayload; response: ProviderSettings };
  YM_SAVE_PROVIDERS: { request: { providers: ProviderSettings }; response: { ok: true } };
  YM_LIST_MODELS: { request: { providerId: ProviderId }; response: { models: ModelInfo[] } };
  YM_GET_PAGE_CACHE: { request: { url: string }; response: { cache?: PageCache } };
  YM_CLEAR_PAGE_CACHE: { request: { url: string }; response: { ok: true } };
  YM_GENERATE_SUMMARY: {
    request: { source: SourcePayload; requestId?: string; traceId?: string; cachePolicy?: SummaryCachePolicy };
    response: { summary: SummaryResult; meta: SummaryMeta; cache: PageCache };
  };
  YM_CLEAR_PAGE_CACHES: { request: NoPayload; response: { ok: true } };
  YM_GET_COMMAND_SHORTCUTS: { request: NoPayload; response: { shortcuts: Record<string, string> } };
  YM_GET_PANEL_STATE: { request: { domain: string }; response: { state?: PanelState } };
  YM_SAVE_PANEL_STATE: { request: { domain: string; state: PanelState }; response: { ok: true } };
  YM_FETCH_SOURCE_BINARY: { request: { url: string }; response: { url: string; bytes: ArrayBuffer; contentType?: string } };
  YM_OPEN_EXTENSION_SHORTCUTS: { request: NoPayload; response: { ok: true } };
  YM_FETCH_BILIBILI_SUBTITLE: { request: { hints: BilibiliSubtitleHints }; response: BilibiliSubtitleResponse };
  YM_FETCH_YOUTUBE_PAGE_TRANSCRIPT: { request: NoPayload; response: YouTubeTranscriptResponse };
  YM_FETCH_YOUTUBE_SUBTITLE: { request: { pageUrl: string }; response: YouTubeTranscriptResponse };
  YM_TRANSLATE_SUBTITLES: {
    request: { sourceTitle: string; segments: SubtitleSegment[]; targetLanguage: SubtitleTranslationTarget };
    response: { segments: TranslatedSubtitleSegment[]; targetLanguage: SubtitleTranslationTarget };
  };
};

export type RuntimeRequest = {
  [K in keyof RuntimeContract]: RuntimeContract[K]["request"] & { type: K };
}[keyof RuntimeContract];

export type TabRequest =
  | { type: "YM_OPEN_PANEL"; autoSummarize: boolean; animate?: boolean }
  | { type: "YM_TOGGLE_PANEL" }
  | { type: "YM_STREAM_CHUNK"; chunk: string; streamKind?: "summary"; requestId: string };

export type TabResponse = { ok: true } | { error: string };

export type RuntimeResponseMap = {
  [K in keyof RuntimeContract]: RuntimeContract[K]["response"];
};

export type RuntimeResponse<T extends RuntimeRequest["type"]> = RuntimeResponseMap[T];

export async function sendRuntimeMessage<T extends RuntimeRequest>(
  request: T
): Promise<RuntimeResponse<T["type"]>> {
  const response = (await chrome.runtime.sendMessage(request)) as unknown;
  if (isErrorResponse(response)) throw new Error(response.error);
  return response as RuntimeResponse<T["type"]>;
}

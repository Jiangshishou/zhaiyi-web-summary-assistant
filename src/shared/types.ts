export type ProviderId = string;
export type ThemeMode = "auto" | "light" | "dark";
export type WebProviderStatus = "unknown" | "available" | "unavailable";
export type ModelThinkingLevel = "disabled" | "enabled" | "standard" | "deep" | "extended" | "high" | "max";
export type OutputCompressionMode = "off" | "lite" | "full" | "ultra";
export type SummaryCachePolicy = "write" | "skip";
export type SourceExtractionStageId = "readable" | "transcript" | "fallback" | "truncation" | "csr-dashboard";
export type SourceExtractionStageStatus = "success" | "warning" | "failed" | "skipped";

export type SourceKind =
  | "page-readable"
  | "youtube-transcript"
  | "bilibili-official-summary"
  | "bilibili-transcript"
  | "douyin-visible"
  | "fallback";

export interface ModelInfo {
  id: string;
  label: string;
  enabled?: boolean;
  thinkingLevels?: ModelThinkingLevel[];
}

export interface ProviderConfig {
  name?: string;
  apiKey: string;
  baseUrl?: string;
  selectedModel: string;
  models: ModelInfo[];
}

export type ProviderSettings = Record<ProviderId, ProviderConfig>;

export interface Settings {
  defaultProvider: ProviderId;
  themeMode: ThemeMode;
  autoSummarize?: boolean;
  shortcut?: string;
  deepseekWebStatus?: WebProviderStatus;
  deepseekWebLastCheckedAt?: number;
  deepseekWebModels?: ModelInfo[];
  modelThinkingLevels?: Record<string, ModelThinkingLevel>;
  pageCacheLimit?: number;
  summaryOutputCompressionMode?: OutputCompressionMode;
  subtitleTranslationTarget?: SubtitleTranslationTarget;
}

export interface SourcePayload {
  url: string;
  title: string;
  authorName?: string;
  authorAvatar?: string;
  favicon?: string;
  /* 这一页的封面图（开放图谱/推特卡片），用于空态卡的预览区 */
  cover?: string;
  published?: string;
  site?: string;
  language?: string;
  sourceKind: SourceKind;
  text: string;
  sourceMarkdown?: string;
  sourceText?: string;
  capturedAt: number;
  warning?: string;
  isAutoGenerated?: boolean;
  segments?: SubtitleSegment[];
  summaryHint?: SummaryResult;
  extractionDiagnostics?: SourceExtractionDiagnostics;
}


export interface SourceExtractionStageFact {
  label: string;
  value: string;
}

export interface SourceExtractionStage {
  id: SourceExtractionStageId;
  status: SourceExtractionStageStatus;
  label: string;
  detail?: string;
  facts?: SourceExtractionStageFact[];
}

export interface SourceExtractionDiagnostics {
  stages: SourceExtractionStage[];
  lowConfidence?: boolean;
}

export interface SubtitleSegment {
  start: number; // seconds
  end: number; // seconds
  text: string;
}

export type SubtitleTranslationTarget = "zh-Hans" | "en";

export interface TranslatedSubtitleSegment extends SubtitleSegment {
  translatedText: string;
}

export interface SummaryPoint {
  text: string;
  children?: SummaryPoint[];
}

export interface SummarySection {
  title: string;
  points: SummaryPoint[];
}

export interface SummaryResult {
  title: string;
  overview: string;
  sections: SummarySection[];
}

export interface SummaryTimingMeta {
  traceId?: string;
  mode?: "direct" | "chunk";
  totalMs: number;
  providerFirstChunkMs?: number;
  providerDurationMs?: number;
  parseDurationMs?: number;
  chunkCount?: number;
  chunkConcurrency?: number;
  chunkDurationMs?: number;
  synthesisDurationMs?: number;
}

export interface SummaryMeta {
  providerId: ProviderId;
  model: string;
  generatedAt: number;
  timing?: SummaryTimingMeta;
}

export interface PageCache {
  source: SourcePayload;
  summary?: SummaryResult;
  summaryMeta?: SummaryMeta;
  cacheKey?: string;
  lastAccessedAt?: number;
}

export interface PanelState {
  left?: number;
  top?: number;
  collapsed?: boolean;
}

export interface BilibiliSubtitleCandidateHint {
  subtitleUrl: string;
  language?: string;
  aiType?: number;
}

export interface BilibiliSubtitleHints {
  pageUrl: string;
  pageSubtitleCandidates?: BilibiliSubtitleCandidateHint[];
}
